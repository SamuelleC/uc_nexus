// Helper function to get schedule for a specific block and year
export const getBlockSchedule = (
  department: string,
  yearLevel: number,
  block: string,
): BlockSchedule | null => {
  const yearKey = String(yearLevel);
  if (
    department.toUpperCase() === "CITCS" &&
    CITCS_SCHEDULES[yearKey] &&
    CITCS_SCHEDULES[yearKey][block]
  ) {
    return CITCS_SCHEDULES[yearKey][block];
  }
  return null;
};
