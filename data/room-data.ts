const SCHOOLDAYS = ['monday', 'tuesday', 'wednesday', 'thursday', 'friday', 'saturday']; 

const generateWeeklyAvailability = (days: string[]): TimeSlot[] => {
    const availability: TimeSlot[] = [];
    for (const day of days) {
        for (const slot of STANDARD_TIME_SLOTS) {
            availability.push({
                day: day as TimeSlot['day'],
                startTime: slot.startTime,
                endTime: slot.endTime,
                isAvailable: true, 
            });
        }
    }
    return availability;
};

